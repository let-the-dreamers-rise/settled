// Day-1 probe M0a, funds-free: reads GET /v0/tokens and asks for a DRY quote (no deposit
// address, nothing can be sent) with no auth header. Writes docs/probe-results.md.
// It never reads a private key and never sends ONECLICK_JWT.
import { mkdirSync, writeFileSync } from "node:fs";
import { MAINNET_ROUTES } from "../packages/sdk/src/assets.js";
import { OneClickClient, OneClickError, type QuoteRequest } from "../packages/sdk/src/oneclick.js";

type Row = { id: number; probe: string; result: "pass" | "fail" | "blocked"; detail: string };

const base = process.env.ONECLICK_API_BASE || undefined;
const client = new OneClickClient({ base }); // deliberately no jwt
const usdc = MAINNET_ROUTES.origin.USDC!;
const baseUsdc = MAINNET_ROUTES.destination["base:USDC"]!;
const now = new Date();

function describeError(e: unknown): string {
  if (e instanceof OneClickError) return `${e.message}; body: ${e.body.slice(0, 200)}`;
  return (e as Error).message;
}

async function tokensRow(): Promise<Row> {
  try {
    const tokens = (await client.tokens()) as { assetId?: string; decimals?: number; symbol?: string; blockchain?: string }[];
    const near = tokens.find((t) => t.assetId === usdc.originAsset);
    const dest = tokens.find((t) => t.assetId === baseUsdc);
    const ok = Boolean(near && dest && near.decimals === usdc.decimals);
    return {
      id: 1,
      probe: "GET /v0/tokens, no auth: USDC-on-NEAR and Base USDC asset ids present",
      result: ok ? "pass" : "fail",
      detail: `${tokens.length} tokens listed; ${usdc.originAsset} ${near ? `found (${near.symbol}, ${near.blockchain}, decimals ${near.decimals})` : "NOT FOUND"}; ${baseUsdc} ${dest ? `found (${dest.symbol}, ${dest.blockchain})` : "NOT FOUND"}`,
    };
  } catch (e) {
    return { id: 1, probe: "GET /v0/tokens, no auth", result: "fail", detail: describeError(e) };
  }
}

async function dryQuoteRow(): Promise<Row> {
  const req: QuoteRequest = {
    dry: true,
    swapType: "EXACT_INPUT",
    slippageTolerance: 100,
    originAsset: usdc.originAsset,
    depositType: "ORIGIN_CHAIN",
    destinationAsset: baseUsdc,
    amount: "2000000",
    // A placeholder; dry quotes have no deposit address, so nothing can be paid to it.
    // 1Click rejects the 0x...dEaD burn address with "recipient is not valid" (seen 2026-11-01).
    recipient: process.env.PROBE_RECIPIENT || "0x1111111111111111111111111111111111111111",
    recipientType: "DESTINATION_CHAIN",
    refundTo: process.env.PAYER_ACCOUNT_ID || "intents.near",
    refundType: "ORIGIN_CHAIN",
    deadline: new Date(now.getTime() + 10 * 60_000).toISOString(),
  };
  try {
    const q = await client.quote(req);
    const out = q.quote.amountOutFormatted ?? q.quote.amountOut;
    return {
      id: 2,
      probe: "POST /v0/quote dry:true, no auth header, 2 USDC (NEAR) -> USDC (Base)",
      result: "pass",
      detail: `accepted without auth; amountOut ${out} for amountIn 2 (difference is fees and spread as quoted); depositAddress ${q.quote.depositAddress ? "present" : "absent (expected for dry)"}; signature ${q.signature ? "present" : "absent"}. No JWT needed for a quote; whether a JWT changes the fee is row 3`,
    };
  } catch (e) {
    const auth = e instanceof OneClickError && (e.httpStatus === 401 || e.httpStatus === 403);
    return {
      id: 2,
      probe: "POST /v0/quote dry:true, no auth header",
      result: "fail",
      detail: `${auth ? "auth required: request a JWT at https://partners.near-intents.org. " : ""}${describeError(e)}`,
    };
  }
}

const BLOCKED: Row[] = [
  { id: 3, probe: "Same quote with Authorization: Bearer and with X-API-Key; fee per header", result: "blocked", detail: "needs ONECLICK_JWT (human requests it); not run" },
  { id: 4, probe: "M0b contract-as-sender: forwarder contract ft_transfer to a real deposit address; status leaves PENDING_DEPOSIT", result: "blocked", detail: "needs a funded mainnet account (M0f, human); not run" },
  { id: 5, probe: "ToS s.4.1 reading", result: "pass", detail: "see docs/tos-reading.md (Verdict line); s.4.1(h) raised there needs a human decision" },
  { id: 6, probe: "M0f funding route to USDC-on-NEAR from India, with fees", result: "blocked", detail: "human task; not run" },
  { id: 7, probe: "Measured gas for ft_transfer_call through Settled", result: "blocked", detail: "M0b; sandbox uses 150 Tgas, mainnet value not measured" },
];

const rows = [await tokensRow(), await dryQuoteRow(), ...BLOCKED].sort((a, b) => a.id - b.id);
const md = [
  "# Probe results",
  "",
  `Generated by \`pnpm probe:quote\` at ${now.toISOString()} against ${base ?? "https://1click.chaindefuser.com"}.`,
  "Rows 1 and 2 are funds-free and run without any credential. Raw 1Click responses are not stored (ToS s.4.1(e)); only the facts below.",
  "Row 2 uses the placeholder recipient 0x1111111111111111111111111111111111111111; 1Click rejected 0x000000000000000000000000000000000000dEaD with HTTP 400 \"recipient is not valid\" on 2026-11-01.",
  "",
  "| # | Probe | Result | Detail |",
  "| --- | --- | --- | --- |",
  ...rows.map((r) => `| ${r.id} | ${r.probe} | ${r.result} | ${r.detail.replace(/\|/g, "/")} |`),
  "",
].join("\n");
mkdirSync("docs", { recursive: true });
writeFileSync("docs/probe-results.md", md);
console.log(md);
process.exit(rows[0]!.result === "pass" && rows[1]!.result === "pass" ? 0 : 1);
